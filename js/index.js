// 临时调课（按天生效）：不写回 scheduleConfig，既能避免破坏每周轮换课表，
// 又能保证云端配置刷新（newConfig）后依然生效，跨天后自动恢复云端配置。
const LESSON_OVERRIDE_STORAGE_KEY = 'lesson_override'

function lessonOverrideDateKey(date = getCurrentEditedDate()) {
    return [
        date.getFullYear(),
        String(date.getMonth() + 1).padStart(2, '0'),
        String(date.getDate()).padStart(2, '0')
    ].join('-')
}

// 读取当日临时调课表（节次下标 -> 科目简称）；日期不是今天时视为过期并清除
function loadLessonOverrides() {
    const today = lessonOverrideDateKey()
    let raw = null
    try {
        raw = JSON.parse(localStorage.getItem(LESSON_OVERRIDE_STORAGE_KEY) || 'null')
    } catch {
        // 数据损坏：立即清除，避免后续每次读取都重复解析同一条无效数据
        localStorage.removeItem(LESSON_OVERRIDE_STORAGE_KEY)
    }
    const valid = raw !== null && typeof raw === 'object' && raw.date === today &&
        raw.changes !== null && typeof raw.changes === 'object'
    if (!valid) {
        if (raw !== null) localStorage.removeItem(LESSON_OVERRIDE_STORAGE_KEY)
        return {}
    }
    return raw.changes
}

// 记录一次临时调课，仅在当天有效
function setLessonOverride(index, subject) {
    const changes = loadLessonOverrides()
    changes[index] = subject
    localStorage.setItem(LESSON_OVERRIDE_STORAGE_KEY, JSON.stringify({
        date: lessonOverrideDateKey(),
        changes: changes
    }))
    return changes
}

// Generated by ChatGPT4
function getCurrentDaySchedule() {
    const date = getCurrentEditedDate();
    const dayOfWeek = getCurrentEditedDay(date); // 0 = Sunday, 1 = Monday, ...
    const weekNumber = weekIndex; // 当前周数
    const dailyClass = scheduleConfig.daily_class[dayOfWeek];
    if (!dailyClass) return [];
    const overrides = loadLessonOverrides();
    return dailyClass.classList.map((subject, index) => {
        // 临时调课优先于每周轮换课表，且不修改原始 classList
        if (Object.prototype.hasOwnProperty.call(overrides, index)) {
            return overrides[index];
        }
        if (Array.isArray(subject)) {
            return subject[weekNumber]; // 处理每周不同的课程
        }
        return subject;
    });
}

function isClassCurrent(startTime, endTime, currentTime) {
    const [startH, startM] = startTime.split(':').map(Number);
    const [endH, endM] = endTime.split(':').map(Number);
    const [currentH, currentM] = currentTime.split(':').map(Number);

    const startMinutes = startH * 60 + startM;
    const endMinutes = endH * 60 + endM;
    const currentMinutes = currentH * 60 + currentM;

    return currentMinutes >= startMinutes && currentMinutes <= endMinutes;
}

function getCurrentTime() {
    const now = getCurrentEditedDate();
    return [
        now.getHours().toString().padStart(2, '0'),
        now.getMinutes().toString().padStart(2, '0'),
        now.getSeconds().toString().padStart(2, '0')
    ].join(':');
}

function setCurrentHighlightExternal(currentHighlight, index, type, fullName, endTime, currentTime, isEnd = false) {
        currentHighlight.index = index;
        currentHighlight.type = type;
        currentHighlight.fullName = fullName;
        currentHighlight.countdown = calculateCountdown(endTime, currentTime);
        currentHighlight.countdownText = formatCountdown(currentHighlight.countdown);
        if (isEnd) currentHighlight.isEnd = true;
    }

function getScheduleData() {
    const currentSchedule = getCurrentDaySchedule();
    const currentTime = getCurrentTime();
    const dayOfWeek = getCurrentEditedDay(getCurrentEditedDate());
    const timetable = scheduleConfig.daily_class[dayOfWeek].timetable;
    const dayTimetable = scheduleConfig.timetable[timetable];
    const divider = scheduleConfig.divider[timetable];
    let scheduleArray = [];
    let currentHighlight = { index: null, type: null, fullName: null, countdown: null, countdownText: null };
    let nextScheduleName = null; // 下一节课的名称

    const timeRanges = Object.keys(dayTimetable);

    const findUpcoming = (breakIndex, breakRange) => {
        // 选择接下来最近的一节课作为 upcoming（高亮位置用下一节课），
        // 但显示的文字应为当前课间/时段在 timetable 中配置的标签。
        let breakLabel = '';
        const curVal = dayTimetable[breakRange];
        if (typeof curVal !== 'number' && curVal) breakLabel = String(curVal);

        // 如果 timetable 没给当前时段配置标签，则尝试向后找第一个字符串标签做为显示
        if (!breakLabel) {
            for (let i = breakIndex; i < timeRanges.length; i++) {
                const v = dayTimetable[timeRanges[i]];
                if (typeof v !== 'number' && v) {
                    breakLabel = String(v);
                    break;
                }
            }
        }
        // 兜底课间标签
        if (!breakLabel) breakLabel = (scheduleConfig['break_label']) || '课间';

        // 选择下一节课用于定位 upcoming 的 index
        for (let i = breakIndex + 1; i < timeRanges.length; i++) {
            const nextTimeRange = timeRanges[i];
            const nextClassIndex = dayTimetable[nextTimeRange];
            if (typeof nextClassIndex === 'number') {
                // 获取下一节课的名称
                const nextSubjectShortName = currentSchedule[nextClassIndex];
                nextScheduleName = scheduleConfig.subject_name[nextSubjectShortName];
                // scheduleArray.length 指向下一节在列表中的位置
                setCurrentHighlightExternal(
                    currentHighlight,
                    scheduleArray.length,
                    'upcoming',
                    breakLabel, // 注意：显示当前课间/标签，而不是下一节课名
                    breakRange.split('-')[1],
                    currentTime
                );
                return true;
            }
        }
        // 没有后续课程：显示 timetable 中「当前时段」配置的文本标签，
        // 既不是恒定“放学”，也不是下一段的标签（取下一段会让整条尾巴错位一格）
        // 1) 优先使用当前时段自身的标签
        let dismissalLabel = '';
        const curVal2 = dayTimetable[breakRange];
        if (typeof curVal2 !== 'number' && curVal2) dismissalLabel = String(curVal2);
        // 2) 当前时段没有标签时，退回后续时段中出现的第一个字符串标签
        if (!dismissalLabel) {
            for (let i = breakIndex + 1; i < timeRanges.length; i++) {
                const v = dayTimetable[timeRanges[i]];
                if (typeof v !== 'number' && v) {
                    dismissalLabel = String(v);
                    break;
                }
            }
        }
        // 3) 仍无则回退到 end_of_day_label 或默认"放学"
        if (!dismissalLabel) dismissalLabel = (scheduleConfig['end_of_day_label']) || '放学';
        setCurrentHighlightExternal(
            currentHighlight,
            Math.max(0, currentSchedule.length - 1),
            'upcoming',
            dismissalLabel,
            breakRange.split('-')[1],
            currentTime,
            true
        );
        return false;
    }

    for (const [index, timeRange] of timeRanges.entries()) {
        const [startTime, endTime] = timeRange.split('-');
        const classIndex = dayTimetable[timeRange];

        if (typeof classIndex === 'number') {
            const subjectShortName = currentSchedule[classIndex];
            const subjectFullName = scheduleConfig.subject_name[subjectShortName];
            scheduleArray.push(subjectShortName);

            if (isClassCurrent(startTime, endTime, currentTime)) {
                setCurrentHighlightExternal(currentHighlight, scheduleArray.length - 1, 'current', subjectFullName, endTime, currentTime);
                // 查找下一节课的名称
                for (let i = index + 1; i < timeRanges.length; i++) {
                    const nextTimeRange = timeRanges[i];
                    const nextClassIndex = dayTimetable[nextTimeRange];
                    if (typeof nextClassIndex === 'number') {
                        const nextSubjectShortName = currentSchedule[nextClassIndex];
                        nextScheduleName = scheduleConfig.subject_name[nextSubjectShortName];
                        break;
                    }
                }
            }
        } else if (currentHighlight.index === null && isBreakTime(startTime, endTime, currentTime)) {
            // 课间：寻找下一节课
            findUpcoming(index, timeRange);
        } else if (currentHighlight.index === null && !dayTimetable[timeRange]) {
            currentHighlight.fullName = currentSchedule[classIndex];
        }
    }

    // 如果没有找到当前课程或课间，尝试设置下一节课的名称
    if (currentHighlight.index === null && nextScheduleName === null) {
        // 查找第一节课作为下一节课
        for (const [index, timeRange] of timeRanges.entries()) {
            const classIndex = dayTimetable[timeRange];
            if (typeof classIndex === 'number') {
                const subjectShortName = currentSchedule[classIndex];
                nextScheduleName = scheduleConfig.subject_name[subjectShortName];
                break;
            }
        }
    }

    return {scheduleArray, currentHighlight, timetable, divider, nextScheduleName};
}


function calculateCountdown(targetTime, currentTime) {
    const [targetH, targetM] = targetTime.split(':').map(Number);
    const [currentH, currentM, currentS = '00'] = currentTime.split(':').map(Number);

    const targetTotalSeconds = targetH * 3600 + (targetM + 1) * 60;
    const currentTotalSeconds = currentH * 3600 + currentM * 60 + currentS;

    return targetTotalSeconds - currentTotalSeconds;
}

function formatCountdown(countdownSeconds) {
    const minutes = Math.floor(countdownSeconds / 60);
    const seconds = countdownSeconds % 60;
    return `${minutes.toString().padStart(2, '0')}:${seconds.toString().padStart(2, '0')}`;
}

// ===== 状态接口（3011 端口 /status）用 =====
// 必须与界面同源：是否在上课、当前/下一节课、下一次上下课时刻都复用 getCurrentDaySchedule /
// getCurrentTime / isClassCurrent / calculateCountdown，避免两套判定各自漂移。

function clockToMinutes(clock) {
    const [hours, minutes] = clock.split(':').map(Number);
    return hours * 60 + minutes;
}

function minutesToClock(minutes) {
    // 故意不取模：23:59 的下课时刻是次日 00:00，用 24:00 表示比 00:00 更不容易误读
    const hours = Math.floor(minutes / 60);
    return `${hours.toString().padStart(2, '0')}:${(minutes % 60).toString().padStart(2, '0')}`;
}

// 简写与全称都可能是 '名称@下角标' 形式（见 scheduleConfig.js 注释，如 '自@语'、'英语@1'）。
// 状态接口输出纯文本：去掉 '@' 标记，但保留下角标字符本身，避免两个同名前缀的科目被合并。
function plainSubjectName(name) {
    return typeof name === 'string' ? name.replaceAll('@', '') : null;
}

function getSubjectFullName(shortName) {
    if (!shortName) return null;
    // 查表必须用带 '@' 的原始简写作为 key，只有输出才归一
    const fullName = (scheduleConfig.subject_name || {})[shortName];
    return plainSubjectName(typeof fullName === 'string' ? fullName : shortName);
}

// 供 /status 使用：把当前状态压成一份可 JSON 序列化的快照
function getScheduleStatus() {
    const now = getCurrentEditedDate();
    const currentTime = getCurrentTime();
    const dayOfWeek = getCurrentEditedDay(now);
    const currentSchedule = getCurrentDaySchedule();
    const [nowHours, nowMinutes, nowSeconds] = currentTime.split(':').map(Number);
    const nowTotalSeconds = nowHours * 3600 + nowMinutes * 60 + nowSeconds;
    const status = {
        time: currentTime,
        timestamp: now.getTime(),
        inClass: false,
        state: 'break',
        currentLesson: null,
        nextLesson: null,
        nextChange: null
    };

    const dailyClass = scheduleConfig.daily_class && scheduleConfig.daily_class[dayOfWeek];
    const dayTimetable = dailyClass && scheduleConfig.timetable && scheduleConfig.timetable[dailyClass.timetable];
    if (!dayTimetable) return status;

    const lessons = Object.keys(dayTimetable)
        // 文本时段（课间/晚读/放学…）的 value 是字符串，不是课程序号，不参与状态判定
        .filter((range) => typeof dayTimetable[range] === 'number' && dayTimetable[range] >= 0)
        .map((range) => {
            const [startTime, endTime] = range.split('-');
            const shortName = currentSchedule[dayTimetable[range]] || null;
            return {
                shortName,
                fullName: getSubjectFullName(shortName),
                startTime,
                endTime,
                startMinutes: clockToMinutes(startTime),
                // 与 calculateCountdown 保持一致：作息表结束时间 +1 分钟才是真实下课时刻
                endMinutes: clockToMinutes(endTime) + 1
            };
        })
        .sort((a, b) => a.startMinutes - b.startMinutes);

    const toView = (lesson) => ({
        fullName: lesson.fullName,
        shortName: plainSubjectName(lesson.shortName),
        startAt: minutesToClock(lesson.startMinutes),
        endAt: minutesToClock(lesson.endMinutes)
    });

    const currentLesson = lessons.find((lesson) => isClassCurrent(lesson.startTime, lesson.endTime, currentTime));
    // 严格晚于当前秒的下一节；课间与上课中都取同一份结果
    const nextLesson = lessons.find((lesson) => lesson.startMinutes * 60 > nowTotalSeconds);
    if (nextLesson) status.nextLesson = toView(nextLesson);

    if (currentLesson) {
        status.inClass = true;
        status.state = 'in_class';
        status.currentLesson = toView(currentLesson);
        status.nextChange = {
            type: 'class_end',
            at: minutesToClock(currentLesson.endMinutes),
            inSeconds: calculateCountdown(currentLesson.endTime, currentTime)
        };
    } else if (nextLesson) {
        status.nextChange = {
            type: 'class_start',
            at: minutesToClock(nextLesson.startMinutes),
            inSeconds: nextLesson.startMinutes * 60 - nowTotalSeconds
        };
    }

    return status;
}
